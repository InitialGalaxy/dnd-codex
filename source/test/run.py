import json, sys
from playwright.sync_api import sync_playwright
seed = json.load(open('seed.json'))
errs=[]
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    pg = b.new_page(viewport={'width':1300,'height':900})
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('console', lambda m: m.type=='error' and errs.append(m.text))
    pg.add_init_script(path='mockdb.js')
    pg.goto('file:///home/claude/lorecodex/index.html')
    pg.wait_for_timeout(300)
    pg.evaluate("""async seed => { const db = await window.claude.use('db'); for (const [p,d] of Object.entries(seed)) await db.doc(p).set(d); }""", seed)
    pg.wait_for_timeout(300)
    pg.goto('file:///home/claude/lorecodex/index.html#world'); pg.wait_for_timeout(300)
    pg.set_input_files('#mapfile', '/mnt/user-data/uploads/dnd/Dryrones 2026-10-13-18-00.map')
    pg.wait_for_function("document.querySelector('table.towns')", timeout=20000)
    print('sizes', pg.evaluate("[...window.__store.entries()].map(([k,v])=>k+':'+JSON.stringify(v).length).join(' ')"))
    pg.screenshot(path='world.png', full_page=False)
    # filter by good
    pg.select_option('#wstate', '9'); pg.wait_for_timeout(200)
    print('rows edariun', pg.evaluate("document.querySelectorAll('table.towns tbody tr').length"))
    pg.click('a[href="#town-9"]'); pg.wait_for_timeout(300)
    pg.screenshot(path='town.png', full_page=True)
    # write lore for town via editor
    pg.click('[data-act=newtown]'); pg.wait_for_timeout(200)
    pg.fill('#ed-body', 'Seat of **House Aldermere**. See [[The Flame Cutter]].')
    pg.fill('#ed-tag', 'edariun'); pg.keyboard.press('Enter')
    pg.click('form[data-form=entry] button[type=submit]'); pg.wait_for_timeout(400)
    print('hash', pg.evaluate('location.hash'))
    fc = [k for k,v in seed.items() if v.get('title')=='The Flame Cutter'][0].split('/')[1]
    pg.goto('file:///home/claude/lorecodex/index.html#entry-'+fc); pg.wait_for_timeout(400)
    print('related sections', pg.evaluate("[...document.querySelectorAll('.rel h3')].map(h=>h.innerText)"))
    print('mentioned', pg.evaluate("document.body.innerText.includes('Mentioned in')"))
    pg.screenshot(path='entry.png', full_page=True)
    pg.goto('file:///home/claude/lorecodex/index.html#library'); pg.wait_for_timeout(300)
    pg.click('[data-act=ftag][data-v=dragon]'); pg.wait_for_timeout(200)
    print('lib dragon cards', pg.evaluate("document.querySelectorAll('.cards .card').length"))
    pg.screenshot(path='library.png')
    pg.goto('file:///home/claude/lorecodex/index.html#tags'); pg.wait_for_timeout(300)
    pg.set_viewport_size({'width':390,'height':844})
    pg.goto('file:///home/claude/lorecodex/index.html#entry-'+fc); pg.wait_for_timeout(300)
    pg.screenshot(path='phone.png')
    b.close()
print('ERRORS', errs)
