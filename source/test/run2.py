    pg.screenshot(path='statblock.png', full_page=True)
    pg.click('[data-act=edit]'); pg.wait_for_timeout(200)
    print('sb fields', pg.evaluate("document.getElementById('sb-ac').value+' | '+document.getElementById('sb-str').value+' | hidden item:'+document.querySelector('.typefields[data-for=item]').hidden"))
    pg.fill('#sb-cr','4 (1,100 XP)'); pg.click('form[data-form=entry] button[type=submit]'); pg.wait_for_timeout(300)
    print('cr saved', pg.evaluate("window.__store.get('entries/cnoxious-darter').statblock.cr"), pg.evaluate("location.hash"))
