import json
from playwright.sync_api import sync_playwright
seed = json.load(open('seed.json'))
errs=[]; U='http://localhost:8765/index.html'
with sync_playwright() as p:
    b = p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
    pg = b.new_page(viewport={'width':1300,'height':900})
    pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.on('console', lambda m: m.type=='error' and errs.append(m.text))
    pg.add_init_script(path='mockdb.js')
    pg.goto(U); pg.wait_for_timeout(400)
    pg.evaluate("""async seed => { const db = await window.claude.use('db'); for (const [p,d] of Object.entries(seed)) await db.doc(p).set(d); }""", seed)
    pg.goto(U+'#world'); pg.wait_for_timeout(300)
    pg.set_input_files('#mapfile', '/mnt/user-data/uploads/dnd/Dryrones 2026-10-13-18-00.map')
    pg.wait_for_function("document.querySelector('table.towns')", timeout=20000)
