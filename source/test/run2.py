    first = lambda: pg.evaluate("[...document.querySelectorAll('table.towns tbody tr')].slice(0,3).map(r=>r.cells[0].innerText.split('\\n')[0]+'/'+r.cells[1].innerText+'/'+r.cells[4].innerText).join(' | ')")
