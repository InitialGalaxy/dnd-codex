from playwright.sync_api import sync_playwright
with sync_playwright() as p:
    b=p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox']); errs=[]
    G=b.new_page(viewport={'width':1440,'height':950}); G.on('pageerror',lambda e:errs.append(str(e)))
    G.goto('http://localhost:3300/#vtt'); G.wait_for_timeout(1000)
    G.click('[data-act=vttnewcamp]'); G.fill('#vaskv','Math'); G.keyboard.press('Enter'); G.wait_for_timeout(1500)
    pid=G.evaluate("VTT.page"); pc=G.evaluate("[...S.chars.keys()][0]")
    eid=G.evaluate("[...S.entries.entries()].find(([k,v])=>v.type==='creature'&&v.statblock)[0]")
    G.evaluate(f"(async()=>{{const e=S.entries.get('{eid}'); await S.db.doc('entries/{eid}').set(Object.assign({{}},e,{{statblock:Object.assign({{}},e.statblock,{{subtitle:'Large beast',con:'16',exhaust:''}})}}));}})()"); G.wait_for_timeout(400)
    G.evaluate(f"vSave('vtttokens/ogre',{{page:'{pid}',layer:'token',x:3,y:3,size:2,img:'',name:'Ogre',ref:'e:{eid}',owner:'',hp:60,hpMax:60,cbars:[{{id:'w1',name:'Ward',cur:20,max:30,color:'#4cc3c9'}}]}})")
    G.evaluate(f"charChange('{pc}', x => {{ x.level = 5; x.caster = {{on:true, kind:'full', ability:'int', used:0}}; x.resources = [{{name:'Ki', style:'slider', max:5, used:0, color:'teal'}}]; }}, false)")
    G.evaluate(f"vSave('vtttokens/hero',{{page:'{pid}',layer:'token',x:8,y:3,size:1,img:'',name:'Hero',ref:'c:{pc}',owner:'{pc}'}})"); G.wait_for_timeout(800)
    bars=lambda pg,i: pg.evaluate(f"vBars(S.vttTokens.get('{i}')).map(b=>b.label+' '+b.cur+'/'+b.max)")
    G.evaluate("VTT.sel={kind:'tok',id:'ogre'}; vRefresh()"); G.wait_for_timeout(300)
    print('GM ogre start', bars(G,'ogre'))
    def op(pg, key, kind, n):
        pg.click(f'.vsbar [data-act=vttbared][data-k="{key}"]'); pg.wait_for_timeout(250)
        pg.fill('.vbared input', str(n)); pg.click(f'.vbared [data-op={kind}]'); pg.wait_for_timeout(500)
        pg.click(f'.vsbar [data-act=vttbared][data-k="{key}"]'); pg.wait_for_timeout(200)
    op(G,'c:w1','sub',10); print(' Ward -10', bars(G,'ogre'))
    op(G,'c:w1','add',25); print(' Ward +25 (caps at max)', bars(G,'ogre'))
    op(G,'c:w1','set',7); print(' Ward set 7', bars(G,'ogre'))
    G.click('.vsbar [data-act=vttbarstep][data-k="c:w1"][data-v="1"]'); G.wait_for_timeout(400); print(' Ward +1 counter', bars(G,'ogre'))
    op(G,'ex','sub',10); print(' Exhaust -10', bars(G,'ogre'))
    op(G,'ex','set',3); print(' Exhaust set 3', bars(G,'ogre'))
    G.click('.vsbar [data-act=vttbared][data-k="ex"]'); G.wait_for_timeout(250); G.locator('.vsbars').screenshot(path='/tmp/bm1.png')
    P=b.new_context(viewport={'width':1280,'height':850}).new_page(); P.on('pageerror',lambda e:errs.append('P '+str(e)))
    P.goto('http://192.0.2.2:3300/'); P.wait_for_timeout(800); P.click('[data-act=srvlogin][data-v=player]'); P.wait_for_timeout(2500)
    P.goto('http://192.0.2.2:3300/#vtt'); P.wait_for_timeout(800); P.click('.vcamp a >> nth=0'); P.wait_for_timeout(1500)
    P.evaluate("VTT.sel={kind:'tok',id:'hero'}; vRefresh()"); P.wait_for_timeout(400)
    print('PLAYER hero start', bars(P,'hero'), 'editable keys', P.evaluate("[...document.querySelectorAll('.vsbar [data-act=vttbared]')].map(e=>e.dataset.k)"))
    op(P,'sp','sub',10); print(' spell points -10', bars(P,'hero'))
    op(P,'r:0','sub',2); print(' Ki -2', bars(P,'hero'))
    P.click('.vsbar [data-act=vttbarstep][data-k="r:0"][data-v="1"]'); P.wait_for_timeout(600); print(' Ki +1', bars(P,'hero'))
    op(P,'sp','set',20); print(' spell points set 20', bars(P,'hero'))
    print(' sheet says', P.evaluate(f"(()=>{{const c=S.chars.get('{pc}'); return [casterOf(c).left, charResHave(c,c.resources[0])]}})()"))
    P.evaluate("VTT.sel={kind:'tok',id:'ogre'}; vRefresh()"); P.wait_for_timeout(300)
    print(' player controls on ogre', P.locator('[data-act=vttbared],[data-act=vttbarstep]').count())
    P.evaluate("VTT.sel={kind:'tok',id:'hero'}; vRefresh()"); P.wait_for_timeout(300); P.locator('.vsbars').screenshot(path='/tmp/bm2.png')
    print('ERRORS', errs); b.close()
